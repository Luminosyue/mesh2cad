import cadquery as cq
import math

plane_1 = cq.Plane(origin=(0.0, 0.0, -0.76), normal=(0.0, 0.0, 1.0), xDir=(0.0, 1.0, 0.0))
sketch_1 = cq.Workplane(plane_1)
