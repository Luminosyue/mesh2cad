loop_1 = loop_1.lineTo(0.25, 0.24933)
loop_1 = loop_1.close()
sketch_2=sketch_2.add(loop_1)
solid_2 = sketch_2.extrude(0.5)
plane_3 = cq.Plane(origin=(0.0, -0.25, 0.0), normal=(0.0, 1.0, 0.0), xDir=(1.0, 0.0, 0.0))
sketch_3 = cq.Workplane(plane_3)
