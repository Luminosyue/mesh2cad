import cadquery as cq
import math

plane_1 = cq.Plane(origin=(-1.0, 0.0, 0.0), normal=(1.0, 0.0, 0.0), xDir=(0.0, -1.0, 0.0))
sketch_1 = cq.Workplane(plane_1)
loop_1 = sketch_1.moveTo(0.25, 0.25)
loop_1 = loop_1.lineTo(-0.25, 0.24867)
loop_1 = loop_1.lineTo(-0.24867, -0.25)
loop_1 = loop_1.lineTo(0.25, -0.24867)
loop_1 = loop_1.lineTo(0.25, 0.24933)
loop_1 = loop_1.close()
sketch_1=sketch_1.add(loop_1)
solid_1 = sketch_1.extrude(0.5)
plane_2 = cq.Plane(origin=(-1.0, 0.0, 0.0), normal=(1.0, 0.0, 0.0), xDir=(0.0, -1.0, 0.0))
