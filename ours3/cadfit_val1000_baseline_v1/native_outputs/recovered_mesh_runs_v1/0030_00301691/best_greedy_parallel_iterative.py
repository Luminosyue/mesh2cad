import cadquery as cq
import math

plane_1 = cq.Plane(origin=(-1.0, 0.0, 0.0), normal=(1.0, 0.0, 0.0), xDir=(0.0, -1.0, 0.0))
sketch_1 = cq.Workplane(plane_1)
loop_1 = sketch_1.moveTo(0.49891, -0.00347)
loop_1 = loop_1.lineTo(-0.16645, -0.00174)
loop_1 = loop_1.lineTo(0.49891, 0.0)
loop_1 = loop_1.close()
