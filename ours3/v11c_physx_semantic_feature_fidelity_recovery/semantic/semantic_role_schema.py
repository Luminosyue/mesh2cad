def normalize_role(value):
    text = str(value or 'UNKNOWN').upper().replace('-', '_').replace(' ', '_')
    synonyms = {'MAIN_WING_LEFT': 'MAIN_WING', 'MAIN_WING_RIGHT': 'MAIN_WING',
                'HORIZONTAL_TAIL_LEFT': 'TAILPLANE', 'HORIZONTAL_TAIL_RIGHT': 'TAILPLANE',
                'HORIZONTAL_STABILIZER': 'TAILPLANE', 'HORIZONTAL_STABILIZER_LEFT': 'TAILPLANE',
                'HORIZONTAL_STABILIZER_RIGHT': 'TAILPLANE',
                'VERTICAL_STABILIZER': 'VERTICAL_TAIL', 'FUSELAGE_LIKE': 'FUSELAGE'}
    return synonyms.get(text, text)

def functional_role(role):
    return ROLE_FUNCTION.get(role, 'UNKNOWN_FUNCTION')
