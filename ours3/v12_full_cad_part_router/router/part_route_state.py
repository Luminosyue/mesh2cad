from enum import Enum


class PartRouteStatus(str, Enum):
    SUCCESS_HIGH_FIDELITY = "SUCCESS_HIGH_FIDELITY"
    SUCCESS_ACCEPTABLE = "SUCCESS_ACCEPTABLE"
    SAFE_BUT_LOW_FIDELITY = "SAFE_BUT_LOW_FIDELITY"
    NO_HIGH_FIDELITY_BUILDER = "NO_HIGH_FIDELITY_BUILDER"
    NO_EXECUTABLE_PLAN = "NO_EXECUTABLE_PLAN"
    UNSUPPORTED_FEATURE = "UNSUPPORTED_FEATURE"
    GEOMETRY_EVIDENCE_INSUFFICIENT = "GEOMETRY_EVIDENCE_INSUFFICIENT"
    SEMANTIC_UNCERTAIN = "SEMANTIC_UNCERTAIN"
    BUILDER_REJECTED = "BUILDER_REJECTED"
    QA_REJECTED = "QA_REJECTED"
    EXECUTION_FAILED = "EXECUTION_FAILED"
    EXTERNAL_RESOURCE_BLOCKED = "EXTERNAL_RESOURCE_BLOCKED"
    INTERNAL_ERROR = "INTERNAL_ERROR"

    @classmethod
    def terminal_values(cls):
        return {x.value for x in cls}
