"""Rebuild this mesh-derived CAD model with CadQuery.
Generated by batch_mesh2cad.py. The included mesh_decimated.stl is the
faceted reconstruction input.
"""
from pathlib import Path
import struct
import cadquery as cq

SEW_TOLERANCE = 1e-7

def rebuild(output_step=None):
    p = Path(__file__).with_name("mesh_decimated.stl")
    b = p.read_bytes()
    n = struct.unpack_from("<I", b, 80)[0]
    if len(b) != 84 + 50*n:
        raise ValueError("Expected binary STL")
    from OCP.BRepBuilderAPI import BRepBuilderAPI_Sewing
    sew = BRepBuilderAPI_Sewing(SEW_TOLERANCE)
    for i in range(n):
        v = struct.unpack_from("<9f", b, 84 + 50*i + 12)
        pts = [cq.Vector(*v[j:j+3]) for j in (0, 3, 6)]
        sew.Add(cq.Face.makeFromWires(cq.Wire.makePolygon(pts, close=True)).wrapped)
    sew.Perform()
    shape = cq.Shape.cast(sew.SewedShape())
    if output_step is None:
        output_step = Path(__file__).with_name("model.step")
    cq.exporters.export(shape, str(output_step))
    return shape

if __name__ == "__main__":
    s = rebuild()
    print({"valid": s.isValid(), "faces": len(s.Faces()), "solids": len(s.Solids())})
